def _strip_comment(line: str) -> str:
    in_single = False
    in_double = False
    out = []
    i = 0
    while i < len(line):
        ch = line[i]
        if ch == "'" and not in_double:
            in_single = not in_single
            out.append(ch)
        elif ch == '"' and not in_single:
            in_double = not in_double
            out.append(ch)
        elif ch == "#" and not in_single and not in_double:
            break
        else:
            out.append(ch)
        i += 1
    return "".join(out).rstrip()


def _parse_scalar(raw: str):
    text = raw.strip()
    if text == "[]":
        return []
    if text.startswith("[") and text.endswith("]"):
        inner = text[1:-1].strip()
        if not inner:
            return []
        return [_parse_scalar(part) for part in _split_top_commas(inner)]
    if (text.startswith('"') and text.endswith('"')) or (
        text.startswith("'") and text.endswith("'")
    ):
        return text[1:-1]
    if text in {"true", "false", "null"}:
        return {"true": True, "false": False, "null": None}[text]
    if text.isdigit() or (text.startswith("-") and text[1:].isdigit()):
        return int(text)
    return text


def _split_top_commas(text: str) -> list[str]:
    parts = []
    buf = []
    depth = 0
    in_single = False
    in_double = False
    for ch in text:
        if ch == "'" and not in_double:
            in_single = not in_single
            buf.append(ch)
        elif ch == '"' and not in_single:
            in_double = not in_double
            buf.append(ch)
        elif ch == "[" and not in_single and not in_double:
            depth += 1
            buf.append(ch)
        elif ch == "]" and not in_single and not in_double:
            depth -= 1
            buf.append(ch)
        elif ch == "," and depth == 0 and not in_single and not in_double:
            parts.append("".join(buf).strip())
            buf = []
        else:
            buf.append(ch)
    if buf:
        parts.append("".join(buf).strip())
    return [p for p in parts if p]


def _indent_of(line: str) -> int:
    return len(line) - len(line.lstrip(" "))


def load_map_yaml(text: str) -> dict:
    raw_lines = text.splitlines()
    lines: list[tuple[int, str]] = []
    for lineno, raw in enumerate(raw_lines, start=1):
        stripped = _strip_comment(raw)
        if not stripped.strip():
            continue
        if "\t" in stripped:
            raise ValueError(f"line {lineno}: tabs are not allowed; use spaces")
        lines.append((lineno, stripped))

    pos = 0

    def peek():
        return lines[pos] if pos < len(lines) else None

    def parse_value(min_indent: int):
        nonlocal pos
        item = peek()
        if item is None:
            return None
        lineno, line = item
        indent = _indent_of(line)
        if indent < min_indent:
            return None
        body = line.strip()
        if body.startswith("- "):
            return parse_list(indent)
        if body == "-":
            return parse_list(indent)
        return parse_mapping(indent)

    def parse_mapping(indent: int) -> dict:
        nonlocal pos
        result: dict = {}
        while pos < len(lines):
            lineno, line = lines[pos]
            cur = _indent_of(line)
            if cur < indent:
                break
            if cur > indent:
                raise ValueError(f"line {lineno}: unexpected indent in mapping")
            body = line.strip()
            if body.startswith("-"):
                break
            if ":" not in body:
                raise ValueError(f"line {lineno}: expected 'key: value', got {body!r}")
            key, rest = body.split(":", 1)
            key = key.strip()
            rest = rest.strip()
            pos += 1
            if rest:
                result[key] = _parse_scalar(rest)
                continue
            nxt = peek()
            if nxt is None:
                result[key] = None
                continue
            n_lineno, n_line = nxt
            n_indent = _indent_of(n_line)
            if n_indent <= indent:
                result[key] = None
                continue
            n_body = n_line.strip()
            if n_body.startswith("-"):
                result[key] = parse_list(n_indent)
            else:
                result[key] = parse_mapping(n_indent)
        return result

    def parse_list(indent: int) -> list:
        nonlocal pos
        result: list = []
        while pos < len(lines):
            lineno, line = lines[pos]
            cur = _indent_of(line)
            if cur < indent:
                break
            if cur > indent:
                raise ValueError(f"line {lineno}: unexpected indent in list")
            body = line.strip()
            if not body.startswith("-"):
                break
            item_body = body[1:].strip()
            pos += 1
            if not item_body:
                nxt = peek()
                if nxt is None:
                    result.append(None)
                    continue
                n_indent = _indent_of(nxt[1])
                if n_indent <= indent:
                    result.append(None)
                else:
                    result.append(parse_value(n_indent))
                continue
            if item_body.startswith("-"):
                raise ValueError(f"line {lineno}: nested dash without indent is unsupported")
            if ":" in item_body and not (
                item_body.startswith("[") or item_body.startswith("'") or item_body.startswith('"')
            ):
                key, rest = item_body.split(":", 1)
                mapping = {key.strip(): _parse_scalar(rest.strip()) if rest.strip() else None}
                nxt = peek()
                if nxt is not None:
                    n_indent = _indent_of(nxt[1])
                    # Continuation keys of this list-map sit deeper than the dash.
                    if n_indent > indent and not nxt[1].strip().startswith("-"):
                        extra = parse_mapping(n_indent)
                        if mapping[key.strip()] is None and key.strip() in extra:
                            mapping.update(extra)
                        else:
                            mapping.update(extra)
                result.append(mapping)
            else:
                result.append(_parse_scalar(item_body))
        return result

    root = parse_mapping(0)
    if pos != len(lines):
        lineno, line = lines[pos]
        raise ValueError(f"line {lineno}: unparsed content: {line!r}")
    return root


