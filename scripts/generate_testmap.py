def check_embedded_js(html: str) -> str | None:
    """Return an error string if the inline script is invalid. None if skipped/ok."""
    start = html.find("<script>")
    end = html.rfind("</script>")
    if start < 0 or end < 0 or end <= start:
        return "missing <script> block"
    js = html[start + len("<script>") : end]
    if re.search(r"function renderTaskCard\s*\(\s*t\s*\)", js):
        return "renderTaskCard parameter shadows translation t()"
    if "if (st && st.id) viewedRunId = st.id" in js or "if (st && st.id) displayedRunId = st.id" in js:
        return "status polling must not retarget the displayed run"
    if re.search(
        r"if \(d\.open\) bindDisplayedRun\(d\.getAttribute\(\"data-id\"\)\);\s*"
        r"if \(d\.open && !d\.dataset\.loaded\)",
        js,
    ):
        return "renderHistory must not rebind confirmation from every open history"
    if "function loadHist(d, selectOnOpen)" in js:
        return "loadHist must not select on every open-history fetch"
    if "if (!d.open) bindDisplayedRun(hid);" not in js:
        return "history confirmation must bind from explicit user open/click, not render order"
    node = shutil.which("node")
    if not node:
        return None
    result = subprocess.run(
        [node, "--check"],
        input=js,
        text=True,
        capture_output=True,
        check=False,
    )
    if result.returncode == 0:
        return None
    return (result.stderr or result.stdout or "node --check failed").strip()


