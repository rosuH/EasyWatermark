def uitest_on_desktop_classpath() -> bool:
    gradle = REPO_ROOT / "shared" / "build.gradle.kts"
    if not gradle.is_file():
        return False
    return "src/uiTest" in gradle.read_text(encoding="utf-8")


def scan_test_classes() -> dict[str, dict]:
    """Simple class name → {fqcn, kind} across uiTest / common / desktop / ios / Android host."""
    index: dict[str, dict] = {}
    for kind, root in _SRC_KIND_ROOTS:
        if not root.is_dir():
            continue
        for path in root.rglob("*.kt"):
            try:
                text = path.read_text(encoding="utf-8")
            except OSError:
                continue
            pkg_m = _KT_PACKAGE_RE.search(text)
            pkg = pkg_m.group(1) if pkg_m else ""
            for name in _KT_CLASS_RE.findall(text):
                fqcn = f"{pkg}.{name}" if pkg else name
                index[name] = {"fqcn": fqcn, "kind": kind}
    return index


def scan_desktop_test_classes() -> dict[str, dict]:
    return scan_test_classes()


def case_class_name(ref: str) -> str:
    return ref.split(".", 1)[0] if "." in ref else ref


def case_token(ref: str) -> str:
    head = case_class_name(ref).strip()
    return head.split()[0] if head else ""


def host_runnable(items: list[dict]) -> list[dict]:
    return [item for item in items if item.get("driver", "host") == "host"]


def device_runnable(items: list[dict]) -> list[dict]:
    return [item for item in items if item.get("driver", "host") != "host"]


def classify_edge_cases(
    edge: dict, index: dict | None = None, platform: str = "desktop"
) -> tuple[list[dict], list[dict]]:
    """Split an edge's cases into console-runnable vs skipped_refs for [platform].

    Host slice: Desktop / iOS L1 (uiTest) plus L0 in that target's test source set.
    Android host: L0 in `app/src/test` only — no L1 (ADR-0032).
    Device slice: iOS XCUITest, Android macrobenchmark journeys, desktop headless.
    L3 and other-platform refs are never silently dropped.
    """
    if platform not in PLATFORMS:
        raise ValueError(f"unknown run platform: {platform}")
    if index is None:
        index = scan_test_classes()
    runnable: list[dict] = []
    skipped: list[dict] = []
    l0_kinds = _L0_KINDS[platform]
    for case in edge.get("cases") or []:
        ref = str(case.get("ref") or "")
        layer = str(case.get("layer") or "")
        plat = case.get("platform")
        token = case_token(ref)
        cls = case_class_name(ref)
        info = index.get(token) or index.get(cls)
        fqcn = (info or {}).get("fqcn") or token or cls
        if plat and plat != platform:
            skipped.append({"ref": ref, "reason": f"{plat}-only"})
            continue
        if layer == "L3":
            skipped.append({"ref": ref, "reason": "L3 is observational / not console-runnable"})
            continue
        if layer == "L2":
            if platform == "ios" and token == L2_IOS_CLASS:
                runnable.append(
                    {"ref": ref, "class": token, "fqcn": token, "driver": "xcuitest"}
                )
                continue
            if platform == "android" and token in L2_ANDROID_CLASSES:
                runnable.append(
                    {
                        "ref": ref,
                        "class": token,
                        "fqcn": ANDROID_JOURNEY_FQCN,
                        "driver": "journey",
                    }
                )
                continue
            if platform == "desktop" and token == L2_DESKTOP_CLASS:
                runnable.append(
                    {"ref": ref, "class": token, "fqcn": token, "driver": "headless"}
                )
                continue
            skipped.append(
                {"ref": ref, "reason": f"L2 is not console-runnable on {platform}"}
            )
            continue
        if layer == "L1":
            if platform == "android":
                skipped.append({"ref": ref, "reason": "Android has no L1 (shared tree is desktop/iOS)"})
                continue
            if (info or {}).get("kind") == "uitest" and not uitest_on_desktop_classpath():
                skipped.append(
                    {
                        "ref": ref,
                        "reason": "L1 uiTest is restored as source but not on :shared:desktopTest classpath",
                    }
                )
                continue
            runnable.append({"ref": ref, "class": token or cls, "fqcn": fqcn, "driver": "host"})
            continue
        if layer == "L0":
            kind = (info or {}).get("kind")
            if kind in l0_kinds:
                runnable.append(
                    {"ref": ref, "class": token or cls, "fqcn": fqcn, "driver": "host"}
                )
            else:
                skipped.append(
                    {
                        "ref": ref,
                        "reason": f"L0 class not on {platform} test classpath",
                    }
                )
            continue
        skipped.append({"ref": ref, "reason": f"unrecognized layer {layer or '?'}"})
    return runnable, skipped


def edge_no_run_message(edge_id: str, skipped: list[dict], platform: str = "desktop") -> str:
    if not skipped:
        return f"edge {edge_id} has no {platform}-runnable cases"
    bits = [f"{s['ref']} ({s['reason']})" for s in skipped[:6]]
    extra = f" +{len(skipped) - 6} more" if len(skipped) > 6 else ""
    return f"edge {edge_id} has no {platform}-runnable cases: {'; '.join(bits)}{extra}"


def edge_no_desktop_message(edge_id: str, skipped: list[dict]) -> str:
    return edge_no_run_message(edge_id, skipped, "desktop")


def resolve_edge_spec(
    edge: dict, index: dict | None = None, platform: str = "desktop"
) -> dict:
    runnable, skipped = classify_edge_cases(edge, index, platform)
    host = host_runnable(runnable)
    classes: list[str] = []
    seen: set[str] = set()
    for item in host:
        fq = item["fqcn"]
        if fq not in seen:
            seen.add(fq)
            classes.append(fq)
    if not classes:
        raise ValueError(edge_no_run_message(edge["id"], skipped, platform))
    gradle = _EDGE_GRADLE[platform]
    cmd = ["./gradlew", gradle["task"]]
    for cls in classes:
        cmd.extend(["--tests", cls])
    cmd.extend(["--max-workers=8", "--rerun-tasks"])
    return {
        "label": f"{edge['id']} ({len(host)} {platform} host case(s))",
        "parse_xml": True,
        "heavy": gradle["heavy"],
        "cmd": cmd,
        "xml_dir": gradle["xml_dir"],
        "xml_base": gradle["xml_base"],
        "skipped_refs": skipped,
        "runnable_refs": [item["ref"] for item in host],
        "runnable_count": len(host),
        "platform": platform,
        "driver": "host",
    }


def resolve_edge_device_meta(
    edge: dict, index: dict | None = None, platform: str = "desktop"
) -> dict | None:
    runnable, skipped = classify_edge_cases(edge, index, platform)
    device = device_runnable(runnable)
    if not device:
        return None
    only_testing: list[str] = []
    seen: set[str] = set()
    for item in device:
        if item.get("driver") == "xcuitest":
            method = item["ref"].split(".", 1)[-1] if "." in item["ref"] else ""
            ident = (
                f"iosAppUITests/{L2_IOS_CLASS}/{method}" if method else f"iosAppUITests/{L2_IOS_CLASS}"
            )
            if ident not in seen:
                seen.add(ident)
                only_testing.append(ident)
    builder = device[0]["driver"]
    return {
        "builder": builder,
        "only_testing": only_testing,
        "runnable_refs": [item["ref"] for item in device],
        "runnable_count": len(device),
        "skipped_refs": skipped,
        "platform": platform,
        "heavy": builder != "headless",
        "label": f"{edge['id']} ({len(device)} {platform} device case(s))",
    }


def _plan_slice(edge: dict, index: dict, platform: str) -> dict:
    runnable, skipped = classify_edge_cases(edge, index, platform)
    host = host_runnable(runnable)
    device = device_runnable(runnable)
    return {
        "runnable_count": len(runnable),
        "host_count": len(host),
        "device_count": len(device),
        "runnable_refs": [item["ref"] for item in runnable],
        "skipped_refs": skipped,
    }


def edge_plans_payload(edges: list[dict]) -> dict[str, dict]:
    index = scan_test_classes()
    plans: dict[str, dict] = {}
    for edge in edges:
        row = {plat: _plan_slice(edge, index, plat) for plat in PLATFORMS}
        desktop = row["desktop"]
        row["runnable_count"] = desktop["runnable_count"]
        row["runnable_refs"] = desktop["runnable_refs"]
        row["skipped_refs"] = desktop["skipped_refs"]
        row["witnesses"] = l1_witnesses_for_edge(edge)
        plans[edge["id"]] = row
    return plans


def l1_witnesses_for_edge(edge: dict) -> list[dict]:
    """Expected L1 witness filenames: Class.method → method.png."""
    out: list[dict] = []
    seen: set[str] = set()
    for case in edge.get("cases") or []:
        if case.get("layer") != "L1":
            continue
        ref = str(case.get("ref") or "")
        if "." not in ref:
            continue
        method = ref.rsplit(".", 1)[-1]
        fname = f"{method}.png"
        if fname in seen:
            continue
        seen.add(fname)
        out.append({"ref": ref, "file": fname})
    return out


