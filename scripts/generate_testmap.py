def _require(cond: bool, message: str) -> None:
    if not cond:
        raise ValueError(message)


def _locale_pair(row: object, key: str) -> dict[str, str]:
    _require(isinstance(row, dict), f"copy {key}: must be a mapping with en/zh")
    en = row.get("en")
    zh = row.get("zh")
    _require(isinstance(en, str) and en.strip(), f"copy {key}: en is required")
    _require(isinstance(zh, str) and zh.strip(), f"copy {key}: zh is required")
    return {"en": en.strip(), "zh": zh.strip()}


def load_copy() -> dict[str, dict[str, dict[str, str]]]:
    if not COPY_PATH.is_file():
        raise ValueError(f"missing {COPY_PATH}")
    data = load_map_yaml(COPY_PATH.read_text(encoding="utf-8"))
    _require(isinstance(data, dict), "copy.yaml root must be a mapping")
    out: dict[str, dict[str, dict[str, str]]] = {"nodes": {}, "edges": {}, "cases": {}}
    for kind in ("nodes", "edges", "cases"):
        block = data.get(kind)
        _require(isinstance(block, dict) and block, f"copy.yaml: {kind} must be a non-empty mapping")
        for key, row in block.items():
            _require(isinstance(key, str) and key, f"copy.yaml: {kind} key is required")
            out[kind][key] = _locale_pair(row, f"{kind}.{key}")
    return out


def validate_copy(copy: dict, nodes: list[dict], edges: list[dict]) -> None:
    node_ids = {n["id"] for n in nodes}
    edge_ids = {e["id"] for e in edges}
    refs = {c["ref"] for e in edges for c in (e.get("cases") or [])}
    for nid in sorted(node_ids):
        _require(nid in copy["nodes"], f"copy.yaml: missing nodes.{nid}")
    for eid in sorted(edge_ids):
        _require(eid in copy["edges"], f"copy.yaml: missing edges.{eid}")
    for ref in sorted(refs):
        _require(ref in copy["cases"], f"copy.yaml: missing cases.{ref}")


def validate_map(data: dict) -> tuple[list[dict], list[dict]]:
    _require(isinstance(data, dict), "root must be a mapping")
    nodes = data.get("nodes")
    edges = data.get("edges")
    _require(isinstance(nodes, list) and nodes, "nodes must be a non-empty list")
    _require(isinstance(edges, list) and edges, "edges must be a non-empty list")

    node_ids: list[str] = []
    for node in nodes:
        _require(isinstance(node, dict), "each node must be a mapping")
        nid = node.get("id")
        _require(isinstance(nid, str) and nid, "node.id is required")
        _require(isinstance(node.get("source"), str) and node["source"], f"node {nid}: source is required")
        states = node.get("states", [])
        _require(states is None or isinstance(states, list), f"node {nid}: states must be a list")
        node_ids.append(nid)
    _require(len(node_ids) == len(set(node_ids)), f"duplicate node ids: {node_ids}")
    node_set = set(node_ids)

    edge_ids: list[str] = []
    for edge in edges:
        _require(isinstance(edge, dict), "each edge must be a mapping")
        eid = edge.get("id")
        _require(isinstance(eid, str) and eid, "edge.id is required")
        edge_ids.append(eid)
        _require(edge.get("from") in node_set, f"edge {eid}: from={edge.get('from')!r} is not a node")
        _require(edge.get("to") in node_set, f"edge {eid}: to={edge.get('to')!r} is not a node")
        trigger = edge.get("trigger")
        _require(isinstance(trigger, dict), f"edge {eid}: trigger is required")
        _require(trigger.get("kind") in TRIGGER_KINDS, f"edge {eid}: trigger.kind must be tag|system|prop")
        _require(isinstance(trigger.get("value"), str) and trigger["value"], f"edge {eid}: trigger.value is required")
        platforms = edge.get("platforms")
        _require(isinstance(platforms, dict), f"edge {eid}: platforms is required")
        for plat in PLATFORMS:
            spec = platforms.get(plat)
            _require(isinstance(spec, dict), f"edge {eid}: platforms.{plat} is required")
            _require(spec.get("drive") in DRIVE_VALUES, f"edge {eid}: platforms.{plat}.drive must be real|seam|none")
        owners = edge.get("owners")
        _require(isinstance(owners, list) and owners, f"edge {eid}: owners must be a non-empty list")
        _require(edge.get("priority") in PRIORITY_VALUES, f"edge {eid}: priority must be core|normal|edge")
        cases = edge.get("cases")
        if cases is None:
            edge["cases"] = []
            cases = edge["cases"]
        _require(isinstance(cases, list), f"edge {eid}: cases must be a list")
        for i, case in enumerate(cases):
            _require(isinstance(case, dict), f"edge {eid}: cases[{i}] must be a mapping")
            _require(case.get("layer") in LAYER_VALUES, f"edge {eid}: cases[{i}].layer must be L0|L1|L2|L3")
            _require(isinstance(case.get("ref"), str) and case["ref"], f"edge {eid}: cases[{i}].ref is required")
            if "platform" in case and case["platform"] is not None:
                _require(case["platform"] in PLATFORMS, f"edge {eid}: cases[{i}].platform must be android|ios|desktop")
            if "dimension" in case and case["dimension"] is not None:
                _require(isinstance(case["dimension"], str), f"edge {eid}: cases[{i}].dimension must be a string")

    _require(len(edge_ids) == len(set(edge_ids)), f"duplicate edge ids: {edge_ids}")
    _require(
        len(edges) == EXPECTED_EDGE_COUNT,
        f"testmap ships exactly {EXPECTED_EDGE_COUNT} edges; map has {len(edges)}",
    )
    return nodes, edges


