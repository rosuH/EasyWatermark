def _best_drive(edge: dict) -> str:
    drives = {edge["platforms"][p]["drive"] for p in PLATFORMS}
    if "real" in drives:
        return "real"
    if "seam" in drives:
        return "seam"
    return "none"


def _drive_label(edge: dict) -> str:
    parts = []
    for plat in PLATFORMS:
        parts.append(f"{plat[0]}:{edge['platforms'][plat]['drive']}")
    return " ".join(parts)


def _case_counts(edge: dict) -> dict[str, int]:
    counts = {p: 0 for p in PLATFORMS}
    counts["all"] = len(edge.get("cases") or [])
    for case in edge.get("cases") or []:
        plat = case.get("platform")
        if plat in counts:
            counts[plat] += 1
        else:
            for p in PLATFORMS:
                counts[p] += 1
    return counts


def _layers_of(edge: dict) -> set[str]:
    return {c["layer"] for c in (edge.get("cases") or [])}


def _cases_at(edge: dict, layer: str) -> list[dict]:
    return [c for c in (edge.get("cases") or []) if c.get("layer") == layer]


def _layer_platforms_label(edge: dict, layer: str) -> str:
    plats: set[str] = set()
    unscoped = False
    for case in _cases_at(edge, layer):
        plat = case.get("platform")
        if plat:
            plats.add(plat)
        else:
            unscoped = True
    if unscoped:
        return "all"
    return ", ".join(p for p in PLATFORMS if p in plats) or "—"


def layer_coverage(edges: list[dict]) -> dict[str, list[dict]]:
    return {layer: [e for e in edges if layer in _layers_of(e)] for layer in ("L0", "L1", "L2", "L3")}


def l1_meaningful_gaps(edges: list[dict]) -> list[dict]:
    return [
        e
        for e in edges
        if e.get("trigger", {}).get("kind") == "tag" and "L1" not in _layers_of(e)
    ]


def l2_meaningful_gaps(edges: list[dict]) -> list[dict]:
    return [
        e
        for e in edges
        if any(e["platforms"][p]["drive"] in {"real", "seam"} for p in PLATFORMS)
        and "L2" not in _layers_of(e)
    ]


def render_mermaid(nodes: list[dict], edges: list[dict]) -> str:
    lines = [
        "%% " + GENERATED_BANNER,
        "flowchart TB",
        "  %% Link stroke: solid green=best real; dashed gold=best seam; dotted gray=all none",
        "  %% Labels: a=android i=ios d=desktop drive",
        "",
        "  subgraph shell [Shell]",
        "    system",
        "    launch",
        "    editor",
        "    about",
        "    gallery",
        "  end",
        "",
        "  subgraph sheets [Editor sheets]",
        "    template_sheet",
        "    text_edit_sheet",
        "    custom_color_sheet",
        "    save_export_sheet",
        "    icon_picker",
        "    add_more_picker",
        "  end",
        "",
        "  subgraph export [Export / platform]",
        "    share_sheet",
        "    crash_recovery",
        "    library_read_upsell",
        "  end",
        "",
    ]
    link_styles = {
        "real": "stroke:#38761d,stroke-width:2px",
        "seam": "stroke:#bf9000,stroke-width:2px,stroke-dasharray:6 4",
        "none": "stroke:#888,stroke-width:1.5px,stroke-dasharray:2 3",
    }
    for edge in edges:
        label = f"{edge['id']}<br/>{_drive_label(edge)}"
        best = _best_drive(edge)
        arrow = "-->" if best == "real" else "-.->"
        lines.append(f"  {edge['from']} {arrow}|{label}| {edge['to']}")
    lines.append("")
    for index, edge in enumerate(edges):
        lines.append(f"  linkStyle {index} {link_styles[_best_drive(edge)]}")

    lines.extend(
        [
            "",
            "  classDef real fill:#d9ead3,stroke:#38761d,color:#1d1d1d",
            "  classDef seam fill:#fff2cc,stroke:#bf9000,color:#1d1d1d",
            "  classDef none fill:#f3f3f3,stroke:#666,color:#1d1d1d,stroke-dasharray:4 3",
            "  class launch,editor,about,gallery,template_sheet,text_edit_sheet,custom_color_sheet,save_export_sheet,library_read_upsell real",
            "  class icon_picker,add_more_picker,share_sheet seam",
            "  class system,crash_recovery none",
        ]
    )
    return "\n".join(lines) + "\n"


def _copy_en(copy: dict, kind: str, key: str) -> str:
    row = (copy.get(kind) or {}).get(key) or {}
    return str(row.get("en") or key)


