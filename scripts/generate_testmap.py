def main() -> int:
    if not MAP_PATH.is_file():
        print(f"error: missing {MAP_PATH}", file=sys.stderr)
        return 1
    try:
        data = load_map_yaml(MAP_PATH.read_text(encoding="utf-8"))
        nodes, edges = validate_map(data)
        copy = load_copy()
        validate_copy(copy, nodes, edges)
        validate_artemis_binding(edges)
        validate_agent_device_binding(edges)
    except ValueError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    mermaid = render_mermaid(nodes, edges)
    (OUT_DIR / "map.mmd").write_text(mermaid, encoding="utf-8")
    (OUT_DIR / "coverage.md").write_text(render_coverage_md(nodes, edges, copy), encoding="utf-8")
    html = render_html(nodes, edges, copy)
    (OUT_DIR / "map.html").write_text(html, encoding="utf-8")
    js_error = check_embedded_js(html)
    if js_error:
        print(f"error: map.html script failed syntax check:\n{js_error}", file=sys.stderr)
        return 1

    covered = layer_coverage(edges)
    print(f"wrote {OUT_DIR / 'map.mmd'}")
    print(f"wrote {OUT_DIR / 'coverage.md'}")
    print(f"wrote {OUT_DIR / 'map.html'}")
    print(f"nodes={len(nodes)} edges={len(edges)}")
    for layer in ("L0", "L1", "L2", "L3"):
        print(f"  {layer}: {len(covered[layer])}/{len(edges)}")
    for edge in edges:
        n = len(edge.get("cases") or [])
        mark = " GAP" if n == 0 else ""
        print(f"  {edge['id']}: {n} cases{mark}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
